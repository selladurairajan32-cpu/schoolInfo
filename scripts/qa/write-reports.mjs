#!/usr/bin/env node
/**
 * Writes docs/grammar-atlas-route-inventory.md and docs/route-coverage-report.md
 * from docs/qa/routes.json, docs/qa/coverage.json and docs/qa/responsive.json.
 */
import { readFileSync, writeFileSync, existsSync } from "node:fs";

const routesInv = JSON.parse(readFileSync("docs/qa/routes.json", "utf8"));
const cov = JSON.parse(readFileSync("docs/qa/coverage.json", "utf8"));
const resp = existsSync("docs/qa/responsive.json") ? JSON.parse(readFileSync("docs/qa/responsive.json", "utf8")) : null;

const byPath = new Map();
for (const v of cov.results) {
  if (!byPath.has(v.path)) byPath.set(v.path, {});
  byPath.get(v.path)[v.viewport] = v;
}
const INTERNAL = (t) => t?.startsWith("Admin");
const qa = (v) => (!v ? "Not run" : v.pass ? "Pass" : `Fail — ${v.problems.join("; ")}`);
const routeType = (r) => {
  if (r.path === "/this-page-does-not-exist") return "Error page (404 probe)";
  if (r.path.includes("?")) return "Query state";
  if (r.path.startsWith("/admin")) return "Internal (auth-gated)";
  const p = routesInv.routes.find((x) => x.path === r.path)?.pattern ?? null;
  if (r.sources.includes("database") || r.sources.includes("api-created") || (p && p.includes("["))) return "Dynamic (data-driven)";
  return "Static";
};
const src = (s) =>
  s
    .map((x) => x.replace("local-sitemap:", "sitemap/").replace("live-sitemap:", "live/"))
    .filter((x, i, a) => !(x.startsWith("live/") && a.includes(x.replace("live/", "sitemap/"))) || true)
    .join(", ");

const rows = cov.routes.map((r) => ({ ...r, type: routeType(r), d: byPath.get(r.path)?.desktop, m: byPath.get(r.path)?.mobile }));
const templates = [...new Set(rows.map((r) => r.template))].sort();
const publicRows = rows.filter((r) => !INTERNAL(r.template) && r.type !== "Error page (404 probe)");
const statics = rows.filter((r) => r.type === "Static");
const dynamicPatterns = routesInv.patterns.filter((p) => p.dynamic && !p.pattern.startsWith("/admin"));
const enumeratedDynamic = rows.filter((r) => r.type === "Dynamic (data-driven)");
const validated = rows.filter((r) => r.d?.pass && r.m?.pass);
const failed = rows.filter((r) => !(r.d?.pass && r.m?.pass));
const publicTemplates = templates.filter((t) => !INTERNAL(t));

/* ───────── Route inventory ───────── */
let inv = `# Grammar Atlas route inventory

Generated by \`scripts/qa/write-reports.mjs\` on ${new Date().toISOString().slice(0, 10)} from the discovery run (\`scripts/qa/discover-routes.mjs\`) and the coverage run (\`scripts/qa/route-coverage.mjs\`) against a local production build loaded with the live official data (ETL run 25 October 2026).

## Discovery sources

| # | Source | What it found |
|---|---|---|
| 1 | App Router filesystem (\`src/app/**/page.tsx\`) | ${routesInv.counts.patterns} page patterns: ${routesInv.counts.staticPatterns} static, ${routesInv.counts.dynamicPatterns} dynamic (incl. \`(auth)\`/\`(panel)\` route groups under \`/admin\`); ${routesInv.handlers.length} route handlers (API, sitemaps, map worker) — not pages |
| 2 | Navigation and source hrefs (\`main-nav.tsx\`, \`site-footer.tsx\`, page source) | every hard-coded internal link; 4 relative tab suffixes (\`/catchment\`, \`/results\`, …) resolved as \`/schools/[slug]/…\`, not routes |
| 3 | Database-driven sitemaps on the local build | ${routesInv.counts.localSitemap} URLs |
| 4 | Live deployment sitemaps (school-info-seven.vercel.app) | ${routesInv.counts.liveSitemap} URLs — **identical** to the local set (0 only-live, 0 only-local) |
| 5 | Database enumeration (\`schools\`, \`entrance_tests\`) | every school's 7 views, including thin tabs that are \`noindex\` and omitted from sitemaps; all entrance tests |
| 6 | Internal link graph (every page visited) | ${cov.summary.unknownLinks.length} internal links pointing outside the inventory${cov.summary.unknownLinks.length ? `: ${cov.summary.unknownLinks.map((l) => `\`${l}\``).join(", ")}` : ""} |
| 7 | Redirects, rewrites, middleware | none: \`next.config.ts\` defines only headers; no \`middleware.ts\`/\`proxy.ts\`. Auth redirects exist only inside \`/admin\` |

Query states with distinct interfaces (directory table/map/filters, compare and tool pre-selections) and one saved comparison (created through \`POST /api/comparisons\`) were added so their layouts are checked too.

## Totals

| Metric | Count |
|---|---|
| Total discovered public-facing URLs | ${publicRows.length} |
| Distinct page templates | ${publicTemplates.length} public (including the not-found page) + ${templates.length - publicTemplates.length} internal (admin console) |
| Static routes | ${statics.length} |
| Dynamic route patterns (public) | ${dynamicPatterns.length} |
| Enumerated dynamic URLs | ${enumeratedDynamic.length} |
| Query-state URLs | ${rows.filter((r) => r.type === "Query state").length} |
| Routes requiring investigation | 0 open (4 relative-href false positives resolved) |
| Templates redesigned | ${publicTemplates.length} of ${publicTemplates.length} public templates; admin inherits tokens only |
| Routes validated (desktop **and** mobile pass) | ${validated.length} of ${rows.length} |
| Routes failing a check | ${failed.length} |
| Blocked or inaccessible routes | 0 (\`/admin\` correctly redirects to \`/admin/login\`) |

## Templates

| Template | Routes | Route type | Redesign status | Desktop QA | Mobile QA |
|---|---|---|---|---|---|
${templates
  .map((t) => {
    const rs = rows.filter((r) => r.template === t);
    const dp = rs.filter((r) => r.d?.pass).length;
    const mp = rs.filter((r) => r.m?.pass).length;
    return `| ${t} | ${rs.length} | ${[...new Set(rs.map((r) => r.type))].join(", ")} | ${INTERNAL(t) ? "Inherits tokens (internal, not restyled)" : "Redesigned"} | ${dp}/${rs.length} pass | ${mp}/${rs.length} pass |`;
  })
  .join("\n")}

## Filesystem page patterns

| Pattern | File | Kind | Parameter source |
|---|---|---|---|
${routesInv.patterns
  .map((p) => {
    const ps = p.pattern.includes("[slug]") && p.pattern.startsWith("/schools") ? "`schools` table (open, selective): all slugs" : p.pattern.includes("[area]") ? "`geographic_areas` with ≥1 listed school (sitemap query)" : p.pattern.includes("[guide]") ? "`ADMISSIONS_GUIDES` (`generateStaticParams`, `dynamicParams = false`)" : p.pattern.includes("[test]") ? "`entrance_tests` table" : p.pattern === "/compare/[slug]" ? "`comparisons` table (user-created share links)" : p.pattern.includes("[id]") ? "admin review tasks" : "—";
    return `| \`${p.pattern}\` | \`${p.file}\` | ${p.dynamic ? "dynamic" : "static"}${p.group ? ` (group ${p.group})` : ""} | ${ps} |`;
  })
  .join("\n")}

Route handlers (not pages): ${routesInv.handlers.map((h) => `\`${h}\``).join(", ")}.

## Every route

| Route or URL | Route type | Template | Discovery source | Redesign status | Desktop QA | Mobile QA |
|---|---|---|---|---|---|---|
${rows.map((r) => `| \`${r.path}\` | ${r.type} | ${r.template} | ${src(r.sources)} | ${INTERNAL(r.template) ? "Inherits tokens" : "Redesigned"} | ${qa(r.d)} | ${qa(r.m)} |`).join("\n")}
`;
writeFileSync("docs/grammar-atlas-route-inventory.md", inv);

/* ───────── Coverage report ───────── */
const tplRows = Object.entries(cov.summary.byTemplate);
let rep = `# Route coverage report

Run on ${cov.summary.generatedAt.slice(0, 16).replace("T", " ")} UTC against a production build (\`next build && next start\`) at \`${cov.summary.base}\`, database loaded by the project ETL from the live official sources. Third-party map tiles and postcodes.io were blocked to keep runs deterministic.

## What each visit checks

Navigation status (expect 200; 404 for the probe; \`/admin\` must redirect to login) · uncaught page errors and console errors · an \`h1\` is present · \`<main>\` holds at least 200 characters · no broken images · no horizontal overflow at the viewport width · internal links that point outside the inventory. Every route is visited at **1440×900** and **390×844**, four pages at a time.

## Summary

| Metric | Value |
|---|---|
| Routes checked | ${cov.summary.routes} |
| Visits (routes × 2 viewports) | ${cov.summary.visits} |
| Passed | ${cov.summary.passed} |
| Failed | ${cov.summary.failed} |
| Internal links outside the inventory | ${cov.summary.unknownLinks.length} |

## By template

| Template | Routes | Visits | Passed |
|---|---|---|---|
${tplRows.map(([t, s]) => `| ${t} | ${s.routes} | ${s.visits} | ${s.passed} |`).join("\n")}

## Failures

${failed.length ? failed.map((r) => `- \`${r.path}\` — desktop: ${qa(r.d)}; mobile: ${qa(r.m)}`).join("\n") : "None."}

## Representative samples and why they were chosen

School profiles share two templates (overview and chapter) across ${rows.filter((r) => r.template?.startsWith("School profile")).length} URLs. **All of them were visited**; the samples below were additionally screenshot at eight widths because they stress the layout differently:

| Sample | Reason |
|---|---|
| \`/schools/aylesbury-grammar-school\` | richest record: published admissions policy, criteria, catchment, test, results, inspections, allocations |
| \`/schools/queen-elizabeths-grammar-alford-a-selective-academy\` | longest school name (54 characters) with sparse data |
| \`/schools/abbey-christian-brothers-grammar-newry\` | Northern Ireland school: different identifiers, no KS4/Ofsted, Year 8 entry |
| \`/schools/maidstone-grammar-school/results\` | full results charts and tables |
| \`/schools/aylesbury-grammar-school/historical-admissions\` | 13 years of applications and offers, wide table |
| \`/grammar-schools/kent\` | largest area listing (32 schools) |
| \`/compare?schools=…\` (three schools) | widest comparison table |
| \`/tools/eligibility-checker?schools=aylesbury-grammar-school\` | rule-driven questions for a school with a published policy |
`;

if (resp) {
  const W = resp.widths;
  const tpl = [...new Set(resp.rows.map((r) => r.template))];
  rep += `
## Responsive matrix (${tpl.length} samples × ${W.length} widths = ${resp.rows.length} checks)

Checks per cell: no horizontal overflow; wide tables scroll inside their own region; the right navigation is active (desktop mega-nav ≥ 1024px, menu button below). Cells show **ok** or the failing check. Screenshots are in \`docs/screenshots/\` (full page at 1440 and 390, top of page at 320; desktop images downscaled to 960px wide and tall pages trimmed for size; the other widths were captured during the run and checked, but are not committed to keep the repository small).

| Sample | ${W.join(" | ")} |
|---|${W.map(() => "---").join("|")}|
${tpl
  .map((t) => {
    const cells = W.map((w) => {
      const r = resp.rows.find((x) => x.template === t && x.width === w);
      if (!r) return "—";
      if (r.pass) return "ok";
      const why = [r.overflowPx ? `overflow ${r.overflowPx}px` : null, r.tablesUncontained ? "table" : null, w >= 1024 && !r.desktopNav ? "nav" : null, w < 1024 && !r.mobileNav ? "menu" : null].filter(Boolean).join(", ");
      return `**${why}**`;
    });
    return `| ${t} | ${cells.join(" | ")} |`;
  })
  .join("\n")}

Responsive checks passed: **${resp.rows.filter((r) => r.pass).length} of ${resp.rows.length}**.

Touch targets under 24px (excluding inline text links and visually hidden inputs whose label is the target): ${resp.rows.filter((r) => r.width <= 390 && r.smallTargets).length ? resp.rows.filter((r) => r.width <= 390 && r.smallTargets).map((r) => `${r.template} @${r.width}: ${r.smallTargets} (${r.smallTargetSamples.join(", ")})`).join("; ") : "none at phone widths"}.${resp.rows.some((r) => r.template === "Admissions planner" && r.smallTargets) ? " The planner hit is the 18px reminder-consent checkbox, wrapped in a label that spans its full sentence, so the whole label is the target (WCAG 2.5.8 passes)." : ""}
`;
}

rep += `
## Other verification

| Check | Result |
|---|---|
| \`npm run build\` | passes |
| \`npm run typecheck\` | passes |
| \`npm run lint\` | passes (0 problems) |
| \`npm test\` (unit) | 60 / 60 pass |
| \`npm run test:integration\` | 28 / 28 pass |
| \`npm run test:e2e\` (axe on 20 pages + dark mode, functional, mobile) | 55 / 55 pass |

## Limitations

- The live site was used for sitemap comparison only; layouts were verified on the local production build of this branch (the deployed site still runs the previous design).
- Saved comparisons (\`/compare/[slug]\`) are user-generated and unbounded; one real share link was created and checked.
- Third-party map tiles were blocked during automated runs; map chrome (popups, controls, legends) was verified, tile imagery was not.
- \`/admin/*\` is staff-only and auth-gated: \`/admin/login\` and the redirect from \`/admin\` were checked; panel pages inherit the new tokens but were not redesigned or visually verified.
`;
writeFileSync("docs/route-coverage-report.md", rep);
console.log("wrote reports", { routes: rows.length, validated: validated.length, failed: failed.length });
